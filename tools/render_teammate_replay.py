"""Render recorded PPO states; independently inspect mesh-decomposition contacts.

MuJoCo is a renderer/contact checker here, NOT the dynamics that generated the
trajectory. No commands, ROS, arming, or course-finish qualification.
"""
import argparse
from hashlib import sha256
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import imageio_ffmpeg
import mujoco
import numpy as np
from PIL import Image, ImageDraw


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--trajectory', required=True, type=Path)
    parser.add_argument('--scene', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    states = np.loadtxt(args.trajectory, delimiter=',', skiprows=1)
    tree = ET.parse(args.scene)
    tree.find('compiler').set('meshdir', str((args.scene.parent/'meshes').resolve()))
    body = tree.find("worldbody/body[@name='proxy_quad']")
    # Preserve visual aircraft, replace its colliders with the teammate's .25/.12
    # cylindrical envelope. Unlike their upright test, this follows actual tilt.
    for geom in body.findall('geom'):
        geom.set('contype', '0')
        geom.set('conaffinity', '0')
    ET.SubElement(body, 'geom', name='review_envelope', type='cylinder',
                  size='.25 .12', rgba='1 .4 .05 .16', contype='1', conaffinity='1', mass='0')
    model = mujoco.MjModel.from_xml_string(ET.tostring(tree.getroot(), encoding='unicode'))
    data = mujoco.MjData(model)
    j = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, 'quad_free')
    address = model.jnt_qposadr[j]
    envelope = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, 'review_envelope')

    def set_pose(t):
        row = np.array([np.interp(t, states[:, 0], states[:, i]) for i in range(1, 11)])
        row[6:10] /= np.linalg.norm(row[6:10])
        data.qpos[address:address+3] = row[:3]
        data.qpos[address+3:address+7] = row[6:10]
        mujoco.mj_forward(model, data)

    contacts = []
    for t in np.arange(0, states[-1, 0]+1e-6, .005):
        set_pose(t)
        for contact in data.contact:
            if envelope in (contact.geom1, contact.geom2) and contact.dist < -1e-5:
                other = contact.geom2 if contact.geom1 == envelope else contact.geom1
                contacts.append({'t_s': float(t), 'geom': mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, other),
                                 'penetration_m': float(-contact.dist)})
    report = {'kind': 'numpy_policy_state_replay_not_mujoco_or_px4_flight',
              'trajectory_sha256': sha256(args.trajectory.read_bytes()).hexdigest(),
              'scene_sha256': sha256(args.scene.read_bytes()).hexdigest(),
              'last_recorded_state_s': float(states[-1, 0]),
              'center_height_range_m': [float(states[:, 3].min()), float(states[:, 3].max())],
              'wall_height_m': 1.7272, 'envelope_radius_m': .25, 'envelope_half_height_m': .12,
              'contact_check_dt_s': .005, 'contacts': contacts,
              'contact_caveat': 'MuJoCo convex decomposition of original mesh, tilted proxy cylinder; not exact Sky Beta swept-volume qualification',
              'landing_and_disarm_observed': False, 'course_finish_qualified': False}
    (args.output/'validation.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    camera = mujoco.MjvCamera()
    camera.lookat[:] = [0, 0, .5]
    camera.distance, camera.elevation, camera.azimuth = 8.3, -64, 90
    width, height, fps = 1280, 720, 50
    writer = imageio_ffmpeg.write_frames(str(args.output/'rollout.mp4'), (width, height), fps=fps,
                                        codec='libx264', macro_block_size=1, output_params=['-crf', '20'])
    writer.send(None)
    try:
        with mujoco.Renderer(model, width=width, height=height) as renderer:
            for frame in range(round((states[-1, 0]+.02)*fps)):
                t = min(frame/fps, states[-1, 0])
                set_pose(t)
                renderer.update_scene(data, camera)
                image = Image.fromarray(renderer.render())
                draw = ImageDraw.Draw(image)
                draw.rectangle((0, 0, width, 72), fill='black')
                draw.text((12, 8), f'TEAMMATE PPO | NUMPY SIM STATE REPLAY | t={t:.2f}s | airborne start -> pad hover', fill='white')
                draw.text((12, 29), 'Original course visualized in MuJoCo; dynamics were generated by teammate simulator. No landing/disarm.', fill='white')
                draw.text((12, 50), f'Max center height {states[:,3].max():.3f}m; walls 1.727m | tilted-envelope contact samples: {len(contacts)}', fill='white')
                if frame == 0:
                    image.save(args.output/'first-frame.png')
                if frame == round(3*fps):
                    image.save(args.output/'mid-frame.png')
                writer.send(np.asarray(image).tobytes())
    finally:
        writer.close()
    print(json.dumps({k:v for k,v in report.items() if k != 'contacts'}, indent=2))
    print('penetrating contact samples', len(contacts))


if __name__ == '__main__':
    main()
