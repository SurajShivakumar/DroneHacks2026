def source_text(path):
    if path:
        raw = Path(path).read_bytes()
    else:
        raw = subprocess.run(["git", "show", f"{SOURCE_COMMIT}:{SOURCE_PATH}"], cwd=REPO, check=True,
                             capture_output=True).stdout
    raw = raw.replace(b"\r\n", b"\n")
    digest = hashlib.sha256(raw).hexdigest()
    assert digest == SOURCE_SHA256, f"source sha256 {digest[:12]} is not v4c's {SOURCE_SHA256[:12]}"
    return raw.decode("utf-8")


def sources_dict(text):
    """The literal _SOURCES dict of a generated single file (parsed, not executed)."""
    tree = ast.parse(text)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "_SOURCES" for t in node.targets):
            return ast.literal_eval(node.value)
    raise AssertionError("no _SOURCES")


def build(source=None):
    src = source_text(source)
    s = src

    def rep(a, b, label):
        nonlocal s
        assert s.count(a) == 1, f"{label}: expected exactly one match in the v4c source"
        s = s.replace(a, b)

    j = s.index('"""', s.index('"""') + 3) + 3
    s = DOC + s[j:]
    rep("from flyx.px4_link import NAN3, find_topic, odom_to_course, yaw_from_q_ned  # noqa: E402",
        "from flyx.px4_link import POSE_FRAME_NED, odom_to_course, rotation_wxyz, yaw_from_q_ned  # noqa: E402",
        "px4_link import")
    i, k = s.index("OUT_TOPICS = {"), s.index("def parse_args(")
    s = s[:i] + HELPERS + s[k:]
    rep(ARGS_OLD, ARGS_NEW, "shadow option")
    rep('''    ap.add_argument("--wall-clock", action="store_true",
                    help="use the system clock instead of /clock (only for tests without a simulator)")
''', "", "wall-clock option")
    i = s.rindex("\ndef main(argv=None):")
    s = s[:i + 1] + MAIN.read_text(encoding="utf-8")
    compile(s, str(OUT), "exec")

    # checks: embedded sources byte-identical, no /fmu in the node part, a single main
    assert sources_dict(s) == sources_dict(src), "embedded _SOURCES differ from v4c"
    for name in ("_PRIOR", "_PRIOR_SHA256", "_CHECKPOINTS", "_PACKAGES", "_MAP_ALTITUDE", "_PRIOR_SHAPE"):
        line = re.search(rf"^{name} = .*$", src, re.M).group(0)
        assert s.count(line) == 1, f"{name} changed"
    node_part = s[s.index("_install_embedded()                 # the planner"):]
    fmu_lines = [ln for ln in node_part.splitlines() if "/fmu" in ln]
    assert fmu_lines == ['FORBIDDEN_PREFIXES = ("/fmu/in", "/skybeta/setpoint")'], \
        f"the node part mentions /fmu outside the forbidden-topic guard: {fmu_lines}"
    assert "/fmu" not in DOC.replace("Never /fmu/in", "").replace("never /fmu/in/*", ""), "docstring"
    assert node_part.count("\ndef main(argv=None):") == 1
    OUT.write_text(s, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(s) / 1024:.0f} KB); embedded _SOURCES == v4c ({len(sources_dict(s))} modules)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", help="v4c file (default: git show 1d44162:pathfinding/flyx/upload_to_flyx.py)")
    build(ap.parse_args().source)
