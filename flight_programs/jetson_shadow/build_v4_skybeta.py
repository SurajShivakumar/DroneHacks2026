"""Build jetson_shadow/upload_to_flyx_v4_skybeta.py from Jolie's FlyX-verified v4c planner.

    python3 jetson_shadow/build_v4_skybeta.py                 # source: git show 1d44162:pathfinding/flyx/upload_to_flyx.py
    python3 jetson_shadow/build_v4_skybeta.py --source FILE   # e.g. flyx_successes/upload_to_flyx_704.py

The source is the file that completed the FlyX course 5/5 (NAVIGATE 119.9 s, run flyx-20261108-025844):
origin/jolie-flyx-v2 at 1d44162 ("v4c"), sha256 feb73d6434da... (== flyx_successes/upload_to_flyx_704.py).
Its stamp says "commit b142eb5" because it was built on top of b142eb5 before v4c was committed; the
file committed AT b142eb5 is different (straight-line back-out) and is NOT the one that flew.

The method is jolie_course/build_skybeta_copy.py's: keep every embedded module (_SOURCES), the map and
the planner process byte for byte, replace only the PX4 I/O (docstring, px4_link import, PX4 topic
table -> ENU/NED helpers, the command line, main()). main() here is skybeta_shadow_main.py.in, which
adds the shadow / fake-armed mode and makes SHADOW the default (--fly to fly).
The source is read, never written.
"""
